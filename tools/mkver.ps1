# Generates obj\Version.g.props from the CADENCE_VERSION environment variable (default "dev").
# Run by build.cmd. The value is read from the environment here (never expanded by cmd.exe) and
# restricted to [0-9A-Za-z.+-] so it is safe to embed in XML.
param([Parameter(Mandatory = $true)][string]$Out)
$v = $env:CADENCE_VERSION
if ([string]::IsNullOrEmpty($v)) { $v = 'dev' }
if ($v.Length -gt 64 -or $v -notmatch '^[0-9A-Za-z.+-]+$') {
    [Console]::Error.WriteLine('ERROR: CADENCE_VERSION may only contain [0-9A-Za-z.+-] (max 64 chars), e.g. 0.1.1 or 0.2.0-rc1')
    exit 1
}
$three = '0.0.0'
$four = '0.0.0.0'
if ($v -match '^(\d{1,5})\.(\d{1,5})\.(\d{1,5})([-+].*)?$') {
    if ([int]$Matches[1] -le 65534 -and [int]$Matches[2] -le 65534 -and [int]$Matches[3] -le 65534) {
        $three = ('{0}.{1}.{2}' -f [int]$Matches[1], [int]$Matches[2], [int]$Matches[3])
        $four = $three + '.0'
    }
}
$lines = @(
    '<Project>',
    '  <!-- generated by tools\mkver.ps1 - do not edit -->',
    '  <PropertyGroup>',
    ('    <InformationalVersion>{0}</InformationalVersion>' -f $v),
    ('    <Version>{0}</Version>' -f $three),
    ('    <AssemblyVersion>{0}</AssemblyVersion>' -f $four),
    ('    <FileVersion>{0}</FileVersion>' -f $four),
    '  </PropertyGroup>',
    '</Project>'
)
[System.IO.File]::WriteAllText($Out, ($lines -join "`r`n") + "`r`n", (New-Object System.Text.UTF8Encoding($false)))
Write-Host ('Version: ' + $v + ' (' + $four + ')')
